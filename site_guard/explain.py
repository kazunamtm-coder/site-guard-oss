"""Plain-language explanations for shop owners.

Every finding is shown to the owner as:
  - how urgent it is (今すぐ / 今週中に / 今月中に / 急ぎではありません)
  - a one-line headline anyone can understand
  - what is happening
  - what happens if it is left alone (the business risk)
  - what the owner should do, including "send this to your web company"
The technical title/detail/fix stay on the Finding and are shown separately
under "制作会社・技術者の方へ", ready to forward.

Rule for the owner-facing text: a ten-year-old should understand it.
No server names, commands or English jargon (tests enforce this).
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

from .models import Finding

# level -> (icon, label)
LEVELS = {
    0: ("🔴", "今すぐ"),
    1: ("🟠", "今週中に"),
    2: ("🟡", "今月中に"),
    3: ("⚪", "急ぎではありません"),
}
_SEV_LEVEL = {"critical": 0, "high": 1, "medium": 2, "low": 3, "info": 3}

ASK_WEB_COMPANY = "自分でやったことがなければ、下の「制作会社・技術者の方へ」の部分を、サイトを作った会社にそのまま送ってください。"
HOW_TO_ACCEPT = ("GitHub の「Actions」→「site-guard」→「Run workflow」を開き、mode で「accept」を選んで実行すると、"
                 "今の状態を「正しい」と登録して、この知らせは止まります。")


@dataclass
class Plain:
    level: int
    headline: str
    what: str
    risk: str
    todo: list[str] = field(default_factory=list)

    @property
    def icon(self) -> str:
        return LEVELS[self.level][0]

    @property
    def label(self) -> str:
        return LEVELS[self.level][1]


def _num(pattern: str, text: str, default: str = "") -> str:
    m = re.search(pattern, text)
    return m.group(1) if m else default


def _path_of(f: Finding) -> str:
    # keys look like "scripts:diff:/checkout/:abc123" or "wordpress:exposed:/.env"
    parts = f.key.split(":")
    return parts[2] if len(parts) > 2 else ""


def explain(f: Finding) -> Plain:
    k, sev = f.key, f.severity
    by_sev = _SEV_LEVEL.get(sev, 3)

    # ---- mail ---------------------------------------------------------------
    if k == "mail:spf":
        return Plain(
            min(1, by_sev), "お店の名前で「にせのメール」を送られやすい状態です",
            "メールには「本当にこのお店から送られたか」を確かめるしくみがあります。"
            "お店のアドレスでは、そのための設定が、ないか、まちがっています。",
            "悪い人がお店の名前で、お客さまに「にせの請求」や「パスワードを盗むメール」を送れます。"
            "お客さまがだまされると、お店の信用が落ちます。",
            ["ドメイン（お店のアドレス）を買った会社の管理画面で、設定を1つ追加する作業です。", ASK_WEB_COMPANY],
        )
    if k == "mail:dmarc":
        return Plain(
            1, "にせのメールを止める設定がありません",
            "「お店の名前を使ったにせのメールが届いたら、受け取らないで」とメール会社に伝える設定が、ありません。",
            "にせのメールが、そのままお客さまに届きます。"
            "また、お店から送る本物のメール（注文の確認など）が、迷惑メールに入りやすくなることもあります。",
            ["ドメイン（お店のアドレス）を買った会社の管理画面で、設定を1つ追加する作業です。", ASK_WEB_COMPANY],
        )
    if k == "mail:dmarc-none":
        return Plain(
            2, "にせのメール対策が「見ているだけ」になっています",
            "にせのメールを見つける設定はありますが、今は記録するだけで、止めてはいません。",
            "にせのメールは、今もお客さまに届いてしまいます。",
            ["2〜4週間ようすを見て、お店の本物のメールがきちんと届いていたら、「止める」設定に切りかえます。",
             "切りかえをまちがえると、本物のメールまで届かなくなるので、制作会社に頼むのが安全です。"],
        )
    if k == "dns:lookup-failed":
        return Plain(
            2, "お店のアドレスの情報を、調べられませんでした",
            "点検のとき、お店のアドレス（ドメイン）の情報を確認できませんでした。一時的なことが多いです。",
            "何日も続く場合は、アドレスの設定がこわれているかもしれません。そのままだと、ホームページもメールも使えなくなります。",
            ["次の点検（3時間後）で消えれば、問題ありません。",
             "次の日になっても続いていたら、ドメイン（お店のアドレス）を買った会社に問い合わせてください。"],
        )

    # ---- DNS changes ----------------------------------------------------------
    if k.startswith(("dns:A:", "dns:AAAA:", "dns:NS:")):
        return Plain(
            0, "お店のホームページの「行き先」が書きかえられました",
            "お店のアドレスを開いた人が、どこのサーバー（ホームページが置いてある場所）に案内されるかの設定が、前回の点検から変わりました。",
            "自分や制作会社が変えたのでなければ、お店のアドレスを乗っ取られたおそれがあります。"
            "お客さまが「にせのお店」に案内され、カード番号やパスワードを入力してしまうかもしれません。",
            ["まず、自分か制作会社が最近この設定を変えたか、すぐに確かめてください。変えていたなら問題ありません。",
             "心当たりがなければ、ドメインを買った会社の管理画面にログインして、パスワードを変え、すぐに問い合わせてください。",
             "ログインできないときは、「乗っ取られたかもしれない」と、その会社のサポートにすぐ連絡してください。"],
        )
    if k.startswith("dns:MX:"):
        return Plain(
            0, "お店あてのメールの「届け先」が書きかえられました",
            "お店のアドレスあてのメールを、どこで受け取るかの設定が、前回の点検から変わりました。",
            "自分や制作会社が変えたのでなければ、お店あてのメール（お客さまからの問い合わせや、パスワード再設定のメールなど）を、"
            "他人に読まれているおそれがあります。",
            ["自分か制作会社が最近メールの設定を変えたか、すぐに確かめてください。変えていたなら問題ありません。",
             "心当たりがなければ、ドメインを買った会社の管理画面のパスワードを変え、すぐに問い合わせてください。"],
        )

    # ---- payment / page scripts -------------------------------------------------
    if k.startswith("scripts:diff:"):
        page = _path_of(f)
        if sev == "critical":
            return Plain(
                0, "支払いページで動くプログラムが変わりました",
                f"お客さまがカード番号を入れるページ（{page}）で動いているプログラムが、前回の点検から変わりました。",
                "自分や制作会社が更新したのでなければ、カード番号を盗むプログラムを仕込まれたおそれがあります。"
                "気づかないままだと、お客さまのカード情報が盗まれ続けます。お店は、お客さまへのおわびや、"
                "カード会社から決済を止められるなど、大きな損害を受けることがあります。",
                ["今日、自分か制作会社が、プラグインやテーマ（ホームページの部品）を更新したか確かめてください。",
                 "更新していたなら、問題ありません。" + HOW_TO_ACCEPT,
                 "心当たりがなければ、すぐに制作会社に連絡して、カード決済をいったん止めてもらってください。"
                 "下の「制作会社・技術者の方へ」の部分も、一緒に送ってください。"],
            )
        return Plain(
            1, "ホームページで動くプログラムが変わりました",
            f"ホームページ（{page}）で動いているプログラムが、前回の点検から変わりました。",
            "自分や制作会社が更新したのでなければ、悪いプログラムを仕込まれたおそれがあります。"
            "お客さまに、にせの画面を見せたり、入力した内容を盗んだりできてしまいます。",
            ["自分か制作会社が、最近プラグインやテーマ（ホームページの部品）を更新したか確かめてください。",
             "更新していたなら、問題ありません。" + HOW_TO_ACCEPT,
             "心当たりがなければ、制作会社に連絡してください。"],
        )
    if k.startswith("scripts:removed:"):
        return Plain(
            3, "ホームページで使うプログラムが減りました（危険は小さいです）",
            "ホームページで動くプログラムが減りました。増えたり、変わったりはしていません。",
            "悪いプログラムは「増える」ものなので、危険は小さいです。プラグインを消したり止めたりした後なら、ふつうのことです。",
            ["心当たりがあれば、" + HOW_TO_ACCEPT, "心当たりがなければ、念のため制作会社に聞いてください。"],
        )
    if k.startswith(("scripts:fetch:", "scripts:status:")):
        page = _path_of(f)
        return Plain(
            1, "ホームページの一部が開けません",
            f"点検で、{page} のページを開こうとしましたが、開けませんでした。",
            "お客さまも、このページを開けていないかもしれません。買い物ができず、売り上げが止まります。",
            ["自分のスマホで、そのページを開いてみてください。",
             "開けなければ、サーバー会社（ホームページを置いている会社）か、制作会社に連絡してください。"],
        )
    if k.startswith("scripts:redirect:") or k == "scripts:cart-failed":
        return Plain(
            1, "支払いページの見張りができていません",
            "支払いページは、カートに商品が入っていないと開けません。そのため、中で動くプログラムを確認できていません。",
            "一番大事な支払いページに、カード番号を盗むプログラムを仕込まれても、気づくことができません。",
            ["「持ち主の確認」がまだなら、先にそちらを済ませてください（別の知らせで届いています）。済むと、自動で点検できるようになります。",
             "持ち主の確認が済んでいるのにこの知らせが続く場合は、制作会社に下の内容を送って、設定を頼んでください。"],
        )

    # ---- certificate / connection ------------------------------------------------
    if k in ("tls:verify-failed", "tls:expired"):
        return Plain(
            0, "ホームページの「鍵マーク」がこわれています" if k == "tls:verify-failed" else "ホームページの「鍵マーク」の期限が切れています",
            "ホームページを安全に見せるための証明書（ブラウザに出る鍵マークのもと）に問題があります。"
            "お客さまの画面に「この接続は安全ではありません」と出ている可能性があります。",
            "警告の画面が出ると、ほとんどのお客さまはそこで帰ってしまいます。売り上げが止まります。",
            ["自分のスマホでホームページを開き、警告が出るか確かめてください。",
             "出たら、すぐにサーバー会社か制作会社に連絡してください。"],
        )
    if k == "tls:expiring":
        days = _num(r"残り(\d+)日", f.title, "数")
        return Plain(
            1 if sev == "high" else 2, f"ホームページの「鍵マーク」の期限が、あと{days}日で切れます",
            "ホームページを安全に見せるための証明書には、期限があります。ふつうは自動で更新されますが、まだ更新されていません。",
            "期限が切れると、お客さまの画面に「安全ではありません」という警告が出て、買い物をしてもらえなくなります。",
            ["多くのサーバー会社は、期限が近づくと自動で更新します。",
             "残りが7日を切ってもこの知らせが続いたら、サーバー会社か制作会社に連絡してください。"],
        )
    if k in ("tls:unreachable", "http:unreachable"):
        return Plain(
            0, "ホームページが開けません",
            "点検で、お店のホームページにつながりませんでした。",
            "お客さまもホームページを見られず、買い物ができない状態かもしれません。",
            ["自分のスマホでホームページを開いてみてください。",
             "開けなければ、サーバー会社か制作会社にすぐ連絡してください。開ければ、一時的なものだった可能性があります。"],
        )

    # ---- WordPress -----------------------------------------------------------
    if k.startswith("wordpress:exposed:"):
        path = _path_of(f)
        return Plain(
            0, "見られてはいけないファイルが、だれでも見られる状態です",
            f"「{path}」というファイルを、だれでも外から開けてしまいます。"
            "このようなファイルには、パスワードや、お金のやりとりに使う「鍵」が書かれていることが多いです。",
            "もし、だれかにすでに見られていたら、その鍵やパスワードを使って、お店のサーバーや決済を乗っ取られるおそれがあります。",
            ["すぐに制作会社に連絡して、ファイルを消してもらってください。",
             "ファイルを消すだけでは足りません。中に書かれていたパスワードや鍵を、すべて新しいものに変えてもらってください。"],
        )
    if k == "wordpress:users-endpoint":
        n = _num(r"(\d+)件", f.title, "")
        who = f"{n}人分の" if n else ""
        return Plain(
            1, "管理画面に入るための「ユーザー名」が、だれでも見られます",
            f"ホームページの管理画面にログインするときに使う名前（{who}ユーザー名）が、外から見える状態です。",
            "悪い人は、名前さえ分かれば、あとはパスワードを当てるだけで管理画面に入れます。"
            "入られると、ページを書きかえられたり、カード番号を盗むプログラムを仕込まれたりします。",
            ["制作会社に「ユーザー名が外から見えないようにしてほしい」と頼んでください。数分で終わる作業です。"],
        )
    if k == "wordpress:xmlrpc":
        return Plain(
            1, "パスワードを何度も試せる「裏口」が開いています",
            "ホームページには、古い連絡用の入り口が残っています。ここを使うと、一度にたくさんのパスワードを試せます。",
            "パスワードを当てられて、管理画面に入られるおそれがあります。",
            ["スマホのアプリからホームページを更新していなければ、閉じても困りません。",
             "制作会社に、下の内容を送って閉じてもらってください。"],
        )
    if k == "wordpress:login-open":
        return Plain(
            2, "ログイン画面は、だれでも見られます（よくあることです）",
            "管理画面に入るためのログイン画面は、だれでも開けます。これ自体は、ほとんどのホームページで同じです。",
            "パスワードだけで守っていると、何度も試されて当てられるおそれがあります。",
            ["管理画面に入れる人全員に、「2段階認証」を設定してください。"
             "ログインのときに、スマホのアプリに出る数字も入れるしくみです。",
             "設定のしかたが分からなければ、制作会社に頼んでください。"],
        )
    if k == "wordpress:readme":
        return Plain(
            3, "ホームページの部品の「説明書」が見えています（危険は小さいです）",
            "ホームページを作るソフトの説明書ファイルが、だれでも見られる状態です。",
            "使っているソフトの種類が分かるだけで、これだけで被害が出ることはほとんどありません。",
            ["急ぎではありません。制作会社に会うときに、ついでに消してもらってください。"],
        )
    if k == "wordpress:generator":
        return Plain(
            3, "ホームページのソフトのバージョンが見えています（危険は小さいです）",
            "ホームページを作るソフトの、バージョン（どの版か）が外から分かります。",
            "古い版を使っていると、その版の弱点をねらわれやすくなります。いつも最新にしていれば、大きな問題ではありません。",
            ["ホームページのソフトとプラグインを、いつも最新にしておいてください。",
             "バージョンを隠したい場合は、制作会社に頼んでください。"],
        )

    # ---- headers -------------------------------------------------------------
    if k.startswith("headers:missing:") or k == "headers:missing":
        n = _num(r"(\d+)件", f.title, "いくつか")
        return Plain(
            2 if sev == "medium" else 3, f"ホームページを守る「追加の設定」が{n}つ足りません",
            "ブラウザに「このホームページは、こうやって守ってね」と伝える設定が、足りません。",
            "これだけで、すぐに被害が出るわけではありません。ただ、ほかの弱点と組み合わさると、"
            "にせの画面を重ねられたり、悪いプログラムが動きやすくなったりします。",
            ["制作会社かサーバー会社に、下の内容を送って、設定を頼んでください。"],
        )
    if k == "headers:csp-report-only":
        return Plain(
            3, "悪いプログラムを止める設定を「ためし運転」しています",
            "ホームページで、許可していないプログラムを止める設定を入れましたが、今は記録するだけのためし運転中です。",
            "ためし運転のあいだは、悪いプログラムを止めません。",
            ["ためし運転で問題がなければ、「止める」設定に切りかえます。切りかえは制作会社に頼んでください。"],
        )

    # ---- setup ---------------------------------------------------------------
    if k == "ownership:unverified":
        return Plain(
            1, "もっとくわしく点検するために、「持ち主の確認」をしてください",
            "今は、だれでも見られる範囲だけを点検しています。お店の持ち主だと確認できると、"
            "支払いページの中や、見られてはいけないファイルがないかまで点検できます。",
            "一番大事な支払いページの見張りと、パスワードなどが書かれたファイルのもれの点検が、できていません。",
            [f.fix, "やり方が分からなければ、この知らせを制作会社に送ってください。"],
        )

    # ---- anything not listed above --------------------------------------------
    return Plain(by_sev, f.title, f.detail or f.title, "くわしくは、下の「制作会社・技術者の方へ」を見てください。",
                 [ASK_WEB_COMPANY])


def tech_block(f: Finding) -> str:
    """The technical part, meant to be forwarded to a web company as-is."""
    lines = [f"項目: {f.title}（{f.severity}）"]
    if f.detail:
        lines.append(f.detail)
    if f.fix:
        lines.append(f"対処: {f.fix}")
    return "\n".join(lines)
